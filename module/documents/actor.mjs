import { askRollMode, rollSuccess } from '../helpers/success.mjs';
import { applyRollPenalty, applyRollCosts } from '../helpers/conditions.mjs';
import { visionTokenChanges } from '../helpers/vision.mjs';

// Actors whose basic abilities are currently being created, so that several
// sheet renders in a row don't create them twice.
const creatingBasics = new Set();

/**
 * Extend the base Actor document by defining a custom roll data structure which is ideal for the Simple system.
 * @extends {Actor}
 */
export class NoQuarterActor extends Actor {
  /**
   * Augment the actor's default getRollData() method by appending the data object
   * generated by its DataModel's getRollData(), or null. Derived data such as
   * success chances is calculated in the DataModels (module/data), so it is
   * available both inside and outside of character sheets.
   * @override
   */
  getRollData() {
    return { ...super.getRollData(), ...(this.system.getRollData?.() ?? null) };
  }

  /**
   * Give the actor's tokens the vision its racial skills grant. These are
   * handed to Foundry alongside any `token.` changes from Active Effects, so
   * they are applied to the tokens without being saved on them; see
   * helpers/vision.mjs.
   * @override
   */
  applyActiveEffects(phase) {
    super.applyActiveEffects(phase);
    if (phase !== 'final') return;
    const senses = this.system.bonuses?.senses;
    const changes = (this.tokenActiveEffectChanges.final ?? []).filter((c) => !c.noQuarterVision);
    if (senses?.size) changes.push(...visionTokenChanges(senses));
    this.tokenActiveEffectChanges.final = changes;
  }

  /**
   * Whether the wound rules apply: always for characters, and for bosses with
   * a boon that grants wounds (the Wounds boon). Other monsters die when their
   * health reaches 0.
   * @type {boolean}
   */
  get usesWounds() {
    if (this.type === 'character') return true;
    return this.#bossBoons('grantsWounds').length > 0;
  }

  /**
   * The boons that give this boss advantage on every d100 check (Powerhouse).
   * Like a condition that forces advantage, but permanent: nothing is used up.
   * @type {Item[]}
   */
  get advantageBoons() {
    return this.#bossBoons('grantsAdvantage');
  }

  /**
   * A boss's boons that have a setting turned on. Only bosses use their boons.
   * @param {string} setting   A boolean field of the boon, such as grantsWounds
   * @returns {Item[]}
   */
  #bossBoons(setting) {
    if (this.type !== 'npc' || !this.system.isBoss) return [];
    return this.items.filter((i) => i.type === 'boon' && i.system[setting]);
  }

  /**
   * The wounds that kill an actor that uses them: its maximum health for a
   * character, and NOQUARTER.monsterMaxWounds for a monster.
   * @type {number}
   */
  get maxWounds() {
    return this.type === 'character' ? this.system.health.max : CONFIG.NOQUARTER.monsterMaxWounds;
  }

  /**
   * The token size, in grid squares, for a monster's size.
   * @param {string} size   A key of NOQUARTER.sizes
   * @returns {{width: number, height: number}|undefined}
   */
  static tokenSize(size) {
    const squares = CONFIG.NOQUARTER.sizes[size]?.token;
    if (squares) return { width: squares, height: squares };
  }

  /**
   * A new monster's tokens start at the size for its size, unless it comes
   * with a token size already (a copy or an import keeps its own).
   * @override
   */
  async _preCreate(data, options, user) {
    const allowed = await super._preCreate(data, options, user);
    if (allowed === false) return false;
    if (this.type !== 'npc' || data.prototypeToken?.width !== undefined) return;
    const size = NoQuarterActor.tokenSize(this.system.size);
    if (size) this.updateSource({ prototypeToken: size });
  }

  /**
   * When health reaches 0 an actor that uses wounds gains a
   * wound and health resets to its
   * maximum, then any damage beyond 0 is applied to the new health. Handled
   * here so it applies however the health change was made.
   * @override
   */
  async _preUpdate(changes, options, user) {
    const allowed = await super._preUpdate(changes, options, user);
    if (allowed === false) return false;

    // Changing a monster's size resizes its tokens. A token's own actor
    // resizes that token instead, in _onUpdate.
    const size = NoQuarterActor.tokenSize(foundry.utils.getProperty(changes, 'system.size'));
    if (size && !this.isToken) changes.prototypeToken = { ...changes.prototypeToken, ...size };

    let health = foundry.utils.getProperty(changes, 'system.health.value');
    if (health === undefined || health > 0) return;

    const max = this.system.health?.max;
    // Without wounds (or with no maximum health to reset to) health stops at 0
    // and the actor is dead; see syncDeath().
    if (!this.usesWounds || !(max > 0)) {
      foundry.utils.setProperty(changes, 'system.health.value', 0);
      return;
    }

    let gained = 0;
    while (health <= 0) {
      gained++;
      health += max;
    }
    const wounds = foundry.utils.getProperty(changes, 'system.wounds') ?? this.system.wounds;
    foundry.utils.setProperty(changes, 'system.health.value', health);
    foundry.utils.setProperty(changes, 'system.wounds', wounds + gained);
  }

  /**
   * Token bars clamp damage at 0, which would lose the overflow that carries
   * over after a wound. Apply health damage unclamped so `_preUpdate` can
   * handle it.
   * @override
   */
  async modifyTokenAttribute(attribute, value, isDelta = false, isBar = true) {
    if (attribute === 'health' && isBar && isDelta && value < 0) {
      const updates = { 'system.health.value': this.system.health.value + value };
      const allowed = Hooks.call(
        'modifyTokenAttribute',
        { attribute, value, isDelta, isBar },
        updates,
        this
      );
      return allowed !== false ? this.update(updates) : this;
    }
    return super.modifyTokenAttribute(attribute, value, isDelta, isBar);
  }

  /** @override */
  _onUpdate(changed, options, userId) {
    super._onUpdate(changed, options, userId);
    const size = NoQuarterActor.tokenSize(changed.system?.size);
    if (size && this.isToken && userId === game.user.id) this.token.update(size);
    // Death depends on health, wounds and maximum health (and for a monster,
    // whether it's a boss), so re-check when any of them could have changed.
    const system = changed.system ?? {};
    const relevant = ['wounds', 'stats', 'health', 'isBoss'];
    if (userId === game.user.id && relevant.some((k) => k in system)) {
      this.syncDeath();
    }
  }

  /**
   * Adding, changing or removing a racial skill can change maximum health, and
   * a boon can decide whether a monster uses wounds, so re-check death then too.
   * @override
   */
  _onCreateDescendantDocuments(parent, collection, documents, data, options, userId) {
    super._onCreateDescendantDocuments(parent, collection, documents, data, options, userId);
    this.#syncDeathAfterItems(documents, userId);
  }

  /** @override */
  _onUpdateDescendantDocuments(parent, collection, documents, changes, options, userId) {
    super._onUpdateDescendantDocuments(parent, collection, documents, changes, options, userId);
    this.#syncDeathAfterItems(documents, userId);
  }

  /** @override */
  _onDeleteDescendantDocuments(parent, collection, documents, ids, options, userId) {
    super._onDeleteDescendantDocuments(parent, collection, documents, ids, options, userId);
    this.#syncDeathAfterItems(documents, userId);
    this.#deleteLinkedSkills(documents, ids, userId);
  }

  /**
   * Removing a racial skill that added a skill, such as a Profession, removes
   * that skill too.
   * @param {Document[]} documents   The deleted descendants
   * @param {string[]} ids           Their ids
   * @param {string} userId          The user who deleted them
   */
  #deleteLinkedSkills(documents, ids, userId) {
    if (userId !== game.user.id) return;
    const skillIds = documents
      .filter((d) => d.type === 'racialSkill' && d.system.skillId)
      .map((d) => d.system.skillId)
      .filter((id) => !ids.includes(id) && this.items.get(id)?.type === 'skill');
    if (skillIds.length) this.deleteEmbeddedDocuments('Item', skillIds);
  }

  /**
   * @param {Document[]} documents   The descendants that changed
   * @param {string} userId          The user who changed them
   */
  #syncDeathAfterItems(documents, userId) {
    const relevant = ['racialSkill', 'boon'];
    if (userId === game.user.id && documents.some((d) => relevant.includes(d.type))) this.syncDeath();
  }

  /**
   * With wounds, an actor is dead once its wounds reach its maximum (see
   * maxWounds).
   * Without them, it is dead once its health reaches 0. Applies or removes the
   * Dead status to match.
   * @returns {Promise<void>}
   */
  async syncDeath() {
    const { health, wounds } = this.system;
    const max = this.maxWounds;
    const dead = this.usesWounds ? max > 0 && wounds >= max : health.value <= 0;
    if (dead === this.statuses.has(CONFIG.specialStatusEffects.DEFEATED)) return;
    await this.toggleStatusEffect(CONFIG.specialStatusEffects.DEFEATED, {
      active: dead,
      overlay: dead,
    });
  }

  /** @override */
  _onCreate(data, options, userId) {
    super._onCreate(data, options, userId);
    if (userId === game.user.id) this.ensureBasicAbilities();
  }

  /**
   * Give a character any of the basic abilities it is missing. Basic abilities
   * made before they had their own icons still show the default one, so that
   * is swapped for theirs; a picture someone chose is left alone.
   * @returns {Promise<void>}
   */
  async ensureBasicAbilities() {
    if (this.type !== 'character' || !this.isOwner) return;
    if (creatingBasics.has(this.id)) return;

    const basics = CONFIG.NOQUARTER.basicAbilities;
    const owned = this.items.filter((i) => i.type === 'ability' && basics[i.system.basicKey]);
    const have = new Set(owned.map((i) => i.system.basicKey));
    const missing = Object.entries(basics)
      .map(([key, basic], index) => ({ key, basic, index }))
      .filter(({ key }) => !have.has(key));
    const defaultIcon = getDocumentClass('Item').DEFAULT_ICON;
    const iconUpdates = owned
      .filter((i) => i.img === defaultIcon)
      .map((i) => ({ _id: i.id, img: basics[i.system.basicKey].img }));
    if (!missing.length && !iconUpdates.length) return;

    creatingBasics.add(this.id);
    try {
      if (iconUpdates.length) await this.updateEmbeddedDocuments('Item', iconUpdates);
      if (!missing.length) return;
      await this.createEmbeddedDocuments(
        'Item',
        missing.map(({ key, basic, index }) => ({
          name: game.i18n.localize(basic.name),
          img: basic.img,
          type: 'ability',
          sort: index * 10,
          system: {
            basicKey: key,
            stat: basic.stat,
            rank: 0,
            staminaCost: 0,
            damage: 1,
          },
        }))
      );
    } finally {
      creatingBasics.delete(this.id);
    }
  }

  /**
   * Whether the actor is fighting in a combat that has started. Unlike core's
   * inCombat this doesn't depend on which combat the user is viewing, and a
   * combat that hasn't begun yet doesn't count.
   * @type {boolean}
   */
  get inStartedCombat() {
    return game.combats.some((c) => c.started && c.getCombatantsByActor(this).length);
  }

  /**
   * Catch a breather: health and stamina back to full and every condition
   * cleared. Wounds stay, and so does Dead, since it follows the wounds (see
   * syncDeath). Not available during combat.
   * @returns {Promise<void>}
   */
  async takeBreather() {
    if (this.inStartedCombat) {
      ui.notifications.warn('NOQUARTER.Breather.InCombat', { localize: true });
      return;
    }
    const updates = { 'system.health.value': this.system.health.max };
    if (this.system.stamina) updates['system.stamina.value'] = this.system.stamina.max;
    await this.update(updates);
    const conditions = this.effects
      .filter((e) => e.statuses.size && !e.statuses.has(CONFIG.specialStatusEffects.DEFEATED))
      .map((e) => e.id);
    if (conditions.length) await this.deleteEmbeddedDocuments('ActiveEffect', conditions);
  }

  /**
   * Make every limited-use ability available again, at the end of a combat.
   * @returns {Promise<void>}
   */
  async resetAbilityUses() {
    const updates = this.items
      .filter((i) => i.type === 'ability' && i.system.used > 0)
      .map((i) => ({ _id: i.id, 'system.used': 0 }));
    if (updates.length) await this.updateEmbeddedDocuments('Item', updates);
  }

  /**
   * Roll d100 against one of the actor's stats (or a monster's single set of
   * chances) and post the result.
   * @param {string} key   The stat key, such as "might"
   * @returns {Promise<Roll|undefined>}
   */
  async rollStat(key) {
    // A monster has a single set of chances instead of individual stats.
    if (this.type === 'npc') {
      const label = game.i18n.localize('NOQUARTER.Check');
      const chances = this.system.chances;
      const asked = await askRollMode({ label, chances, actor: this });
      if (!asked) return;
      await applyRollCosts(this, asked);
      return rollSuccess({ actor: this, label, chances: applyRollPenalty(chances, asked.penalty), mode: asked.mode });
    }

    const stat = this.system.stats?.[key];
    if (!stat) return;

    const label = game.i18n.localize(CONFIG.NOQUARTER.stats[key]);
    const asked = await askRollMode({ label, chances: stat.target, actor: this });
    if (!asked) return;
    await applyRollCosts(this, asked);
    return rollSuccess({
      actor: this,
      label,
      chances: applyRollPenalty(stat.target, asked.penalty),
      mode: asked.mode,
    });
  }
}
